/**
 * ShiftLeaderRole — 勤務帯ごとの「責任者ロール」（解決済み）
 *
 * 「早番には早番責任者（早責）が、夜番（運用上は遅番）には夜番責任者（夜責）が、
 *  各稼働日に最低1人入っていなければならない」という責任者要件を表す値。
 *
 * このロールは「表示ラベル」「担当する勤務帯名」「その役割の責任者であるスタッフID」
 * だけを持つ素朴な値とする。スタッフのどのフラグを見て責任者を選ぶか等の解決は上位層
 * （会社ごとの設定）で行い、ここには解決済みの leaderStaffIds を渡す。
 *
 * いずれ会社ごとに注入できるよう、ドメインはこの解決済みの形だけを知っていればよい。
 */
export type ShiftLeaderRole = {
  /** 一意キー（例: "middle" / "night"） */
  key: string;
  /** 表示ラベル（例: "早責" / "夜責"） */
  label: string;
  /** 担当する勤務帯の名前（例: "中番" / "遅番"） */
  shiftName: string;
  /** この役割の責任者であるスタッフID（解決済み） */
  leaderStaffIds: string[];
};
